"""## **10. Aprobación del crédito**"""

# Definir si el crédito no se aprueba, se aprueba de contado o a crédito
def aprobado(esta_en_ofac, nivel_riesgo, edad):
    if edad < 18 or esta_en_ofac=="si":
        return 'no aprobado'
    elif nivel_riesgo=="alto":
        return 'aprobado de contado'
    else:
        return 'aprobado a credito'

"""## **11. Definición de valor_pedido, cupo_aprobado y plazo según riesgo y estado de aprobación**"""

# C
consolidado['valor_pedido'] = consolidado['cupo_preaprobado']

def calcular_cupo(row):

    if row['aprobacion'] == 'no aprobado' or row['nivel_riesgo'] == 'alto':
        return 0
    elif row['nivel_riesgo'] == 'medio':
        return row['cupo_preaprobado'] * 0.50
    elif row['nivel_riesgo'] == 'bajo':
        return row['cupo_preaprobado'] * 1.00
    return 0

def calcular_plazo(row):
    # Si no es aprobado o tiene riesgo alto -> Plazo 0 días
    if row['aprobacion'] == 'no aprobado' or row['nivel_riesgo'] == 'alto':
        return '0 días'
    elif row['nivel_riesgo'] == 'medio':
        return '15 días'
    elif row['nivel_riesgo'] == 'bajo':
        return '45 días'
    return '0 días'

consolidado['cupo_aprobado'] = consolidado.apply(calcular_cupo, axis=1)
consolidado['plazo'] = consolidado.apply(calcular_plazo, axis=1)


