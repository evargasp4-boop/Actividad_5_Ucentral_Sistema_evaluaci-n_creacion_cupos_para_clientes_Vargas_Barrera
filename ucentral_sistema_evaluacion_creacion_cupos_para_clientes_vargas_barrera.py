"""## **7. Asignación del nivel de riesgo**"""

# Función para clasificar el nivel de riesgo de acuerdo con los parametros establecidos por la compañía
def clasificar_riesgos(ingresos_ano_anterior, egresos_ano_anterior, valor_credito_mora, numero_cuotas_mora):

    if ingresos_ano_anterior <= 0 or egresos_ano_anterior < 0:
        return 'alto'

    elif (ingresos_ano_anterior > egresos_ano_anterior and valor_credito_mora <= ingresos_ano_anterior * 1.50 and numero_cuotas_mora <= 4):
        return 'bajo'

    elif (ingresos_ano_anterior > egresos_ano_anterior and (valor_credito_mora <= ingresos_ano_anterior * 2.00 or numero_cuotas_mora <= 6)):
        return 'medio'

    else:
        return 'alto'


consolidado["nivel_riesgo"] = consolidado[
    ["ingresos_ano_anterior",
     "egresos_ano_anterior",
     "valor_credito_mora",
     "numero_cuotas_mora"]
].apply(lambda fila: clasificar_riesgos(*fila), axis=1)

