sample_clients.head()

# Con el objetivo de evitar diferencias en el orden de nombres y apellidos que puedan afectar el cruce, se ordenan de manera alfabetica las palabras que componen el nombre.
def ordenar_nombre(texto):
   if texto in ['nan', 'sin_informacion']:
        return texto
   return ' '.join(sorted(texto.split()))

ofac_list['name'] = ofac_list['name'].apply(ordenar_nombre)

